-- Manual closes supersede any outstanding automatic-close job.
create or replace function public.close_thesis(
  p_thesis_id bigint,
  p_user_id uuid,
  p_close_price numeric
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  thesis_row public.theses%rowtype;
  entry_price numeric;
  close_return numeric;
  active_days integer;
  closed_at timestamptz := clock_timestamp();
  updated_data jsonb;
begin
  select * into thesis_row
  from public.theses
  where id = p_thesis_id and user_id = p_user_id
  for update;

  if not found then return null; end if;
  if thesis_row.status = 'closed' then
    raise exception using errcode = 'P0001', message = 'thesis_already_closed';
  end if;
  if p_close_price is null or p_close_price <= 0 then
    raise exception using errcode = '22003', message = 'invalid_close_price';
  end if;

  entry_price := nullif(thesis_row.data ->> 'entry', '')::numeric;
  close_return := case
    when entry_price is null or entry_price = 0 then coalesce((thesis_row.data ->> 'ret')::numeric, 0)
    else round(
      (case when thesis_row.data ->> 'side' = 'bear' then -1 else 1 end)
      * ((p_close_price - entry_price) / entry_price) * 100,
      1
    )
  end;
  active_days := greatest(0, current_date - nullif(thesis_row.data ->> 'entryDate', '')::date);

  updated_data := thesis_row.data || jsonb_build_object(
    'status', 'closed',
    'closedAt', closed_at,
    'closePrice', p_close_price,
    'closeReturn', close_return,
    'current', p_close_price,
    'ret', close_return,
    'daysActive', active_days
  );

  update public.theses
  set data = updated_data, status = 'closed', version = version + 1,
      refresh_lease_token = null, refresh_lease_expires_at = null
  where id = p_thesis_id and user_id = p_user_id;

  update public.lifecycle_jobs
  set status = 'completed', completed_at = closed_at, next_attempt_at = null,
      lease_token = null, lease_expires_at = null, last_error_code = null,
      updated_at = closed_at
  where thesis_id = p_thesis_id and kind = 'close' and status <> 'completed';

  return updated_data || jsonb_build_object('id', thesis_row.id, 'ownerId', thesis_row.user_id);
end;
$$;

-- Create worker records for valid close dates sealed before this migration.
-- Their timezone is resolved by the worker from the current market snapshot.
with legacy_close_dates as (
  select
    theses.*,
    case when data ->> 'closeDate' ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' then
      case when substring(data ->> 'closeDate', 1, 4)::integer between 1970 and 9999
        and substring(data ->> 'closeDate', 6, 2)::integer between 1 and 12
        and substring(data ->> 'closeDate', 9, 2)::integer between 1 and 31 then
        case when to_char(to_date(data ->> 'closeDate', 'YYYY-MM-DD'), 'YYYY-MM-DD') = data ->> 'closeDate'
          then to_date(data ->> 'closeDate', 'YYYY-MM-DD')
          else null
        end
      else null
      end
    else null
    end as parsed_close_date
  from public.theses
)
insert into public.lifecycle_jobs (
  user_id, kind, status, scheduled_date, thesis_id, resolved_symbol,
  exchange, exchange_timezone, next_attempt_at
)
select
  user_id,
  'close',
  'pending',
  parsed_close_date,
  id,
  coalesce(nullif(data ->> 'resolvedSymbol', ''), nullif(data ->> 'ticker', ''), 'UNKNOWN'),
  data ->> 'exchange',
  'UTC',
  clock_timestamp()
from legacy_close_dates as theses
where status = 'active'
  and parsed_close_date is not null
  and not exists (
    select 1 from public.lifecycle_jobs jobs
    where jobs.kind = 'close' and jobs.thesis_id = theses.id and jobs.status <> 'completed'
  );

