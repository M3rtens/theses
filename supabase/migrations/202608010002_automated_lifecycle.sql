create or replace function public.fail_lifecycle_job(
  p_job_id bigint,
  p_lease_token uuid,
  p_error_code text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  job_row public.lifecycle_jobs%rowtype;
  next_count integer;
  next_status text;
  retry_delay interval;
begin
  select * into job_row
  from public.lifecycle_jobs
  where id = p_job_id and status = 'processing' and lease_token = p_lease_token
  for update;
  if not found then return null; end if;

  next_count := job_row.attempt_count + 1;
  next_status := case when next_count >= 10 then 'action_required' else 'pending' end;
  retry_delay := case next_count
    when 1 then interval '15 minutes'
    when 2 then interval '30 minutes'
    when 3 then interval '1 hour'
    when 4 then interval '2 hours'
    when 5 then interval '4 hours'
    else interval '6 hours'
  end;

  update public.lifecycle_jobs
  set status = next_status,
      attempt_count = next_count,
      next_attempt_at = case when next_status = 'pending' then clock_timestamp() + retry_delay else null end,
      lease_token = null,
      lease_expires_at = null,
      last_error_code = left(coalesce(p_error_code, 'provider_unavailable'), 100),
      updated_at = clock_timestamp()
  where id = p_job_id;

  if next_status = 'action_required' then
    insert into public.notifications (
      user_id, type, title, message, thesis_id, lifecycle_job_id, event_key
    ) values (
      job_row.user_id,
      'action_required',
      'Scheduled action needs attention',
      case job_row.kind
        when 'publish' then 'Publication could not obtain valid market data. Review the schedule and retry.'
        else 'Scheduled close could not obtain valid market data. Retry when the feed is available.'
      end,
      job_row.thesis_id,
      job_row.id,
      format('lifecycle:%s:action:%s', job_row.id, job_row.retry_cycle)
    ) on conflict (event_key) do nothing;
  end if;

  return jsonb_build_object('status', next_status, 'attemptCount', next_count);
end;
$$;

create or replace function public.finalize_publication_job(
  p_job_id bigint,
  p_market jsonb,
  p_lease_token uuid default null,
  p_user_id uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  job_row public.lifecycle_jobs%rowtype;
  new_thesis public.theses%rowtype;
  published_at timestamptz := clock_timestamp();
  market_time timestamptz;
  market_date date;
  entry_price numeric;
  published_data jsonb;
begin
  select * into job_row
  from public.lifecycle_jobs
  where id = p_job_id and kind = 'publish'
  for update;
  if not found then return null; end if;

  if p_user_id is not null then
    if job_row.user_id <> p_user_id or job_row.status not in ('draft', 'pending', 'action_required') then
      raise exception using errcode = 'P0001', message = 'scheduled_publication_not_publishable';
    end if;
  elsif p_lease_token is null
    or job_row.status <> 'processing'
    or job_row.lease_token <> p_lease_token then
    raise exception using errcode = 'P0001', message = 'invalid_lifecycle_lease';
  end if;

  entry_price := nullif(p_market ->> 'price', '')::numeric;
  market_time := nullif(p_market ->> 'marketTime', '')::timestamptz;
  if entry_price is null or entry_price <= 0 or market_time is null then
    raise exception using errcode = '22023', message = 'invalid_market_snapshot';
  end if;
  if p_user_id is null and (
    coalesce(p_market ->> 'marketState', '') <> 'REGULAR'
    or market_time < clock_timestamp() - interval '30 minutes'
    or market_time > clock_timestamp() + interval '5 minutes'
  ) then
    raise exception using errcode = '22023', message = 'ineligible_market_snapshot';
  end if;
  market_date := (market_time at time zone job_row.exchange_timezone)::date;
  if market_date < job_row.scheduled_date and p_user_id is null then
    raise exception using errcode = '22023', message = 'market_snapshot_before_schedule';
  end if;

  published_data := job_row.payload || jsonb_build_object(
    'company', coalesce(nullif(job_row.payload ->> 'company', ''), p_market ->> 'company', job_row.resolved_symbol),
    'sector', coalesce(nullif(job_row.payload ->> 'sector', ''), p_market ->> 'sector', '—'),
    'publishDate', to_char(published_at at time zone job_row.exchange_timezone, 'Mon FMDD, YYYY'),
    'entryDate', market_date::text,
    'daysActive', 0,
    'entry', entry_price,
    'current', entry_price,
    'ret', 0,
    'status', 'active',
    'updates', 0,
    'currency', coalesce(nullif(p_market ->> 'currency', ''), 'USD'),
    'resolvedSymbol', coalesce(nullif(p_market ->> 'resolvedSymbol', ''), job_row.resolved_symbol),
    'exchange', coalesce(p_market ->> 'exchange', job_row.exchange),
    'createdAt', published_at
  );

  insert into public.theses (user_id, data, status, next_refresh_at)
  values (job_row.user_id, published_data, 'active', clock_timestamp())
  returning * into new_thesis;

  update public.lifecycle_jobs
  set status = 'completed',
      thesis_id = new_thesis.id,
      completed_at = published_at,
      next_attempt_at = null,
      lease_token = null,
      lease_expires_at = null,
      last_error_code = null,
      updated_at = published_at
  where id = job_row.id;

  insert into public.notifications (
    user_id, type, title, message, thesis_id, lifecycle_job_id, event_key
  ) values (
    job_row.user_id,
    'publication_completed',
    'Thesis published',
    format('%s was published and its entry price was sealed.', coalesce(job_row.payload ->> 'title', job_row.resolved_symbol)),
    new_thesis.id,
    job_row.id,
    format('lifecycle:%s:completed', job_row.id)
  ) on conflict (event_key) do nothing;

  return published_data || jsonb_build_object(
    'id', new_thesis.id,
    'ownerId', new_thesis.user_id,
    'lifecycleJobId', job_row.id
  );
end;
$$;

