create or replace function public.claim_lifecycle_jobs(
  p_lease_token uuid,
  p_limit integer default 25
)
returns setof public.lifecycle_jobs
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  return query
  with candidates as (
    select id
    from public.lifecycle_jobs
    where (
        status = 'pending'
        or (status = 'processing' and lease_expires_at <= clock_timestamp())
      )
      and next_attempt_at <= clock_timestamp()
      and scheduled_date <= (
        clock_timestamp() at time zone coalesce(nullif(exchange_timezone, ''), 'UTC')
      )::date
    order by next_attempt_at, id
    for update skip locked
    limit greatest(1, least(coalesce(p_limit, 25), 25))
  )
  update public.lifecycle_jobs as jobs
  set status = 'processing',
      lease_token = p_lease_token,
      lease_expires_at = clock_timestamp() + interval '10 minutes',
      updated_at = clock_timestamp()
  from candidates
  where jobs.id = candidates.id
  returning jobs.*;
end;
$$;

