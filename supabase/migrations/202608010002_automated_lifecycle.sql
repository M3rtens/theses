begin;

create table if not exists public.lifecycle_jobs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  kind text not null check (kind in ('publish', 'close')),
  status text not null default 'pending'
    check (status in ('draft', 'pending', 'processing', 'action_required', 'completed')),
  scheduled_date date not null,
  payload jsonb,
  thesis_id bigint references public.theses (id) on delete cascade,
  resolved_symbol text not null,
  exchange text,
  exchange_timezone text not null,
  attempt_count integer not null default 0 check (attempt_count >= 0),
  retry_cycle integer not null default 0 check (retry_cycle >= 0),
  next_attempt_at timestamptz,
  lease_token uuid,
  lease_expires_at timestamptz,
  last_error_code text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz,
  constraint lifecycle_job_payload check (
    (kind = 'publish' and payload is not null)
    or (kind = 'close' and thesis_id is not null)
  )
);

create index if not exists lifecycle_jobs_due_idx
  on public.lifecycle_jobs (status, next_attempt_at, id);

create index if not exists lifecycle_jobs_owner_idx
  on public.lifecycle_jobs (user_id, created_at desc, id desc);

create unique index if not exists lifecycle_jobs_open_close_idx
  on public.lifecycle_jobs (thesis_id)
  where kind = 'close' and status <> 'completed';

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  type text not null check (type in (
    'publication_completed', 'close_completed', 'trigger_clear',
    'trigger_warning', 'trigger_breached', 'action_required'
  )),
  title text not null,
  message text not null,
  thesis_id bigint references public.theses (id) on delete cascade,
  lifecycle_job_id bigint references public.lifecycle_jobs (id) on delete cascade,
  event_key text not null unique,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists notifications_owner_created_idx
  on public.notifications (user_id, created_at desc, id desc);

create index if not exists notifications_owner_unread_idx
  on public.notifications (user_id, created_at desc)
  where read_at is null;

alter table public.theses
  add column if not exists next_refresh_at timestamptz not null default now(),
  add column if not exists refresh_lease_token uuid,
  add column if not exists refresh_lease_expires_at timestamptz,
  add column if not exists last_refreshed_at timestamptz,
  add column if not exists refresh_failure_count integer not null default 0;

create index if not exists theses_refresh_due_idx
  on public.theses (next_refresh_at, id)
  where status = 'active';

alter table public.lifecycle_jobs enable row level security;
alter table public.notifications enable row level security;

drop policy if exists "Users can read their own lifecycle jobs" on public.lifecycle_jobs;
create policy "Users can read their own lifecycle jobs"
  on public.lifecycle_jobs for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users can read their own notifications" on public.notifications;
create policy "Users can read their own notifications"
  on public.notifications for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users can mark their own notifications read" on public.notifications;
create policy "Users can mark their own notifications read"
  on public.notifications for update
  to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

revoke all on public.lifecycle_jobs from public, anon, authenticated;
grant select on public.lifecycle_jobs to authenticated;

revoke all on public.notifications from public, anon, authenticated;
grant select on public.notifications to authenticated;
grant update (read_at) on public.notifications to authenticated;

