      scheduled_date = p_scheduled_date,
      resolved_symbol = p_resolved_symbol,
      exchange = p_exchange,
      exchange_timezone = p_exchange_timezone,
      status = case when p_activate then 'pending' else 'draft' end,
      attempt_count = 0,
      retry_cycle = retry_cycle + 1,
      next_attempt_at = case when p_activate then clock_timestamp() else null end,
      lease_token = null,
      lease_expires_at = null,
      last_error_code = null,
      updated_at = clock_timestamp()
  where id = p_job_id
  returning * into job_row;

  return to_jsonb(job_row);
end;
$$;

