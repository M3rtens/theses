create or replace function public.finalize_close_job(
  p_job_id bigint,
  p_market jsonb,
  p_lease_token uuid
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  job_row public.lifecycle_jobs%rowtype;
  thesis_row public.theses%rowtype;
  entry_price numeric;
  close_price numeric;
  close_return numeric;
  market_time timestamptz;
  market_date date;
  closed_at timestamptz := clock_timestamp();
  updated_data jsonb;
begin
  select * into job_row
  from public.lifecycle_jobs
  where id = p_job_id and kind = 'close' and status = 'processing'
    and lease_token = p_lease_token
  for update;
  if not found then return null; end if;

  select * into thesis_row
  from public.theses
  where id = job_row.thesis_id and user_id = job_row.user_id
  for update;
  if not found then return null; end if;

  if thesis_row.status = 'closed' then
    update public.lifecycle_jobs
    set status = 'completed', completed_at = clock_timestamp(), next_attempt_at = null,
        lease_token = null, lease_expires_at = null, updated_at = clock_timestamp()
    where id = job_row.id;
    return thesis_row.data || jsonb_build_object('id', thesis_row.id, 'ownerId', thesis_row.user_id);
  end if;

  close_price := nullif(p_market ->> 'price', '')::numeric;
  market_time := nullif(p_market ->> 'marketTime', '')::timestamptz;
  if close_price is null or close_price <= 0 or market_time is null then
    raise exception using errcode = '22023', message = 'invalid_market_snapshot';
  end if;
  if coalesce(p_market ->> 'marketState', '') <> 'REGULAR'
    or market_time < clock_timestamp() - interval '30 minutes'
    or market_time > clock_timestamp() + interval '5 minutes' then
    raise exception using errcode = '22023', message = 'ineligible_market_snapshot';
  end if;
  market_date := (market_time at time zone job_row.exchange_timezone)::date;
  if market_date < job_row.scheduled_date then
    raise exception using errcode = '22023', message = 'market_snapshot_before_schedule';
  end if;

  entry_price := nullif(thesis_row.data ->> 'entry', '')::numeric;
  close_return := case
    when entry_price is null or entry_price = 0 then coalesce((thesis_row.data ->> 'ret')::numeric, 0)
    else round(
      (case when thesis_row.data ->> 'side' = 'bear' then -1 else 1 end)
      * ((close_price - entry_price) / entry_price) * 100,
      1
    )
  end;

  updated_data := thesis_row.data || jsonb_build_object(
    'status', 'closed',
    'closedAt', closed_at,
    'closePrice', close_price,
    'closeReturn', close_return,
    'current', close_price,
    'ret', close_return,
    'daysActive', greatest(0, market_date - nullif(thesis_row.data ->> 'entryDate', '')::date)
  );

  update public.theses
  set data = updated_data,
      status = 'closed',
      version = version + 1,
      refresh_lease_token = null,
      refresh_lease_expires_at = null
  where id = thesis_row.id;

  update public.lifecycle_jobs
  set status = 'completed', completed_at = closed_at, next_attempt_at = null,
      lease_token = null, lease_expires_at = null, last_error_code = null,
      updated_at = clock_timestamp()
  where id = job_row.id;

  insert into public.notifications (
    user_id, type, title, message, thesis_id, lifecycle_job_id, event_key
  ) values (
    job_row.user_id,
    'close_completed',
    'Thesis closed',
    format('%s closed automatically at its first eligible market session.', coalesce(thesis_row.data ->> 'title', job_row.resolved_symbol)),
    thesis_row.id,
    job_row.id,
    format('lifecycle:%s:completed', job_row.id)
  ) on conflict (event_key) do nothing;

  return updated_data || jsonb_build_object('id', thesis_row.id, 'ownerId', thesis_row.user_id);
end;
$$;

create or replace function public.claim_thesis_refreshes(
  p_lease_token uuid,
  p_limit integer default 25
)
returns table (id bigint, user_id uuid, data jsonb, lease_token uuid)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  return query
  with candidates as (
    select theses.id
    from public.theses
    where theses.status = 'active'
      and theses.next_refresh_at <= clock_timestamp()
      and (theses.refresh_lease_expires_at is null or theses.refresh_lease_expires_at <= clock_timestamp())
    order by theses.next_refresh_at, theses.id
    for update skip locked
    limit greatest(1, least(coalesce(p_limit, 25), 25))
  )
  update public.theses as theses
  set refresh_lease_token = p_lease_token,
      refresh_lease_expires_at = clock_timestamp() + interval '10 minutes'
  from candidates
  where theses.id = candidates.id
  returning theses.id, theses.user_id, theses.data, theses.refresh_lease_token;
end;
$$;

create or replace function public.apply_thesis_refresh(
  p_thesis_id bigint,
  p_lease_token uuid,
  p_patch jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  thesis_row public.theses%rowtype;
  updated_data jsonb;
  old_triggers jsonb;
  new_triggers jsonb;
  trigger_index integer;
  old_status text;
  new_status text;
  trigger_condition text;
  notification_title text;
begin
  if coalesce(p_patch, '{}'::jsonb) - array['current', 'ret', 'daysActive', 'triggers'] <> '{}'::jsonb then
    raise exception using errcode = '22023', message = 'unsupported_metrics_patch';
  end if;

  select * into thesis_row
  from public.theses
  where id = p_thesis_id and status = 'active' and refresh_lease_token = p_lease_token
  for update;
  if not found then return null; end if;

  old_triggers := case
    when jsonb_typeof(thesis_row.data -> 'triggers') = 'array' then thesis_row.data -> 'triggers'
    else '[]'::jsonb
  end;
  new_triggers := case
    when jsonb_typeof(p_patch -> 'triggers') = 'array' then p_patch -> 'triggers'
    else old_triggers
  end;

  if jsonb_array_length(new_triggers) > 0 then
    for trigger_index in 0..jsonb_array_length(new_triggers) - 1 loop
      old_status := coalesce(old_triggers -> trigger_index ->> 's', 'clear');
      new_status := coalesce(new_triggers -> trigger_index ->> 's', 'clear');
      if old_status is distinct from new_status and new_status in ('clear', 'warning', 'breached') then
        trigger_condition := coalesce(new_triggers -> trigger_index ->> 'c', 'A thesis trigger');
        notification_title := case new_status
          when 'breached' then 'Trigger breached'
          when 'warning' then 'Trigger warning'
          else 'Trigger cleared'
        end;
        insert into public.notifications (
          user_id, type, title, message, thesis_id, event_key
        ) values (
          thesis_row.user_id,
          'trigger_' || new_status,
          notification_title,
          format('%s moved from %s to %s.', trigger_condition, old_status, new_status),
          thesis_row.id,
          format('trigger:%s:%s:%s:%s', thesis_row.id, thesis_row.version + 1, trigger_index, new_status)
        ) on conflict (event_key) do nothing;
      end if;
    end loop;
  end if;

  updated_data := thesis_row.data || coalesce(p_patch, '{}'::jsonb);
  update public.theses
  set data = updated_data,
      version = version + case when updated_data is distinct from thesis_row.data then 1 else 0 end,
      last_refreshed_at = clock_timestamp(),
      next_refresh_at = clock_timestamp() + interval '15 minutes',
      refresh_failure_count = 0,
      refresh_lease_token = null,
      refresh_lease_expires_at = null
  where id = thesis_row.id;

  return updated_data || jsonb_build_object('id', thesis_row.id, 'ownerId', thesis_row.user_id);
end;
$$;

